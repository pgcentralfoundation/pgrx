//! Publish one documentation snapshot covering every supported PostgreSQL version.
//!
//! docs.rs builds pgrx-pg-sys without PostgreSQL or Clang, so release generation
//! stores a documentation view of each version's generated C macros. Each macro
//! becomes a shell with its original documentation and invocation forms; the
//! generated implementation and its native support stay out of the snapshot.
//!
//! A shell that is identical in several versions is written once and gated to those
//! versions with `cfg(any(feature = ...))`. Different versions of one macro sit next
//! to each other in its header's module. Before rendering, selecting each version
//! from the merged snapshot must reproduce exactly that version's output.

use super::macro_files::{Directory, HeaderPaths, MacroFiles, cfg_attribute};
use eyre::eyre;
use pgrx_c_macros::{EmissionStatus, MacroDocumentation, MacroEmission};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;
use std::path::{Path, PathBuf};

/// Comment starting every snapshot file.
const PREAMBLE: &str =
    "// Automatically generated by pgrx-c-macros for documentation. Do not hand-edit.\n";

/// One PostgreSQL version's documentation-facing generated output.
pub(super) struct SnapshotVersion {
    /// PostgreSQL major version, matching its `pgNN` feature.
    major: u16,
    /// Public macro documentation keyed by defining header and Rust identifier.
    macros: BTreeMap<(PathBuf, String), MacroDocumentation>,
    /// `__pgrx_c_types` aliases: C typedef name to runtime marker.
    typedefs: BTreeMap<String, &'static str>,
    /// Binding-relative paths of `__pgrx_c_callbacks` typedef aliases.
    callbacks: BTreeSet<Vec<String>>,
}

/// Collect one version's documentation from its emitted macros.
impl SnapshotVersion {
    /// Record each emitted macro under its header relative to `header_root`.
    pub(super) fn new(
        major: u16,
        emissions: &[MacroEmission],
        header_root: &Path,
        typedefs: BTreeMap<String, &'static str>,
        callbacks: BTreeSet<Vec<String>>,
    ) -> eyre::Result<Self> {
        let mut headers = HeaderPaths::new(header_root);
        let mut macros = BTreeMap::new();
        let mut identifiers = BTreeSet::new();
        for emission in emissions {
            let EmissionStatus::Emitted { documentation, .. } = &emission.status else {
                continue;
            };
            if !identifiers.insert(documentation.identifier.clone()) {
                return Err(eyre!(
                    "pg{major} generated macro identifier {} occurs more than once",
                    documentation.identifier
                ));
            }
            let header = headers.relative(&emission.analysis)?;
            macros.insert((header, documentation.identifier.clone()), (**documentation).clone());
        }
        Ok(Self { major, macros, typedefs, callbacks })
    }
}

/// One macro definition shared by several versions.
struct Variant<'a> {
    /// Documentation of the first version defining it; others differ at most in location.
    documentation: &'a MacroDocumentation,
    /// Defining location in each version that has this definition.
    locations: BTreeMap<u16, Option<&'a str>>,
}

/// All versions merged into one header tree.
struct Merged<'a> {
    /// Every version in the snapshot.
    all: BTreeSet<u16>,
    /// Definitions of each macro in each header, ordered by their first version.
    macros: BTreeMap<(&'a Path, &'a str), Vec<Variant<'a>>>,
    /// Typedef markers and the versions using each one.
    typedefs: BTreeMap<&'a str, BTreeMap<&'static str, BTreeSet<u16>>>,
    /// Callback typedef paths and the versions defining each one.
    callbacks: BTreeMap<&'a [String], BTreeSet<u16>>,
}

/// Compare everything except the defining location.
fn same_definition(left: &MacroDocumentation, right: &MacroDocumentation) -> bool {
    left.identifier == right.identifier
        && left.title == right.title
        && left.body == right.body
        && left.forms == right.forms
        && left.hidden == right.hidden
}

/// Merge identical definitions across versions, keeping per-version locations.
fn merge(versions: &[SnapshotVersion]) -> eyre::Result<Merged<'_>> {
    let all = versions.iter().map(|version| version.major).collect::<BTreeSet<_>>();
    if all.len() != versions.len() {
        return Err(eyre!("a PostgreSQL version occurs more than once in the snapshot"));
    }
    let mut merged = Merged {
        all,
        macros: BTreeMap::new(),
        typedefs: BTreeMap::new(),
        callbacks: BTreeMap::new(),
    };
    for version in versions {
        for ((header, identifier), documentation) in &version.macros {
            let variants =
                merged.macros.entry((header.as_path(), identifier.as_str())).or_default();
            let location = documentation.location.as_deref();
            match variants
                .iter_mut()
                .find(|variant| same_definition(variant.documentation, documentation))
            {
                Some(variant) => {
                    variant.locations.insert(version.major, location);
                }
                None => variants.push(Variant {
                    documentation,
                    locations: BTreeMap::from([(version.major, location)]),
                }),
            }
        }
        for (name, marker) in &version.typedefs {
            merged
                .typedefs
                .entry(name.as_str())
                .or_default()
                .entry(*marker)
                .or_default()
                .insert(version.major);
        }
        for path in &version.callbacks {
            merged.callbacks.entry(path.as_slice()).or_default().insert(version.major);
        }
    }
    Ok(merged)
}

/// Prove the merged snapshot loses nothing and gates each name exclusively.
///
/// Selecting one version's definitions from the merged snapshot must reproduce that
/// version's macros, locations, typedefs, and callbacks. The definitions of one macro
/// must have disjoint version sets whose union is the set of versions defining it.
fn verify(versions: &[SnapshotVersion], merged: &Merged<'_>) -> eyre::Result<()> {
    for version in versions {
        let major = version.major;
        let mut projected = BTreeMap::new();
        for ((header, identifier), variants) in &merged.macros {
            for variant in variants {
                let Some(location) = variant.locations.get(&major) else { continue };
                let mut documentation = variant.documentation.clone();
                documentation.location = location.map(str::to_owned);
                if projected
                    .insert((header.to_path_buf(), identifier.to_string()), documentation)
                    .is_some()
                {
                    return Err(eyre!("pg{major} selects two definitions of {identifier}"));
                }
            }
        }
        if projected != version.macros {
            return Err(eyre!("the merged snapshot does not reproduce pg{major}'s macros"));
        }
        let typedefs = merged
            .typedefs
            .iter()
            .flat_map(|(name, markers)| {
                markers
                    .iter()
                    .filter(|(_, versions)| versions.contains(&major))
                    .map(|(marker, _)| (name.to_string(), *marker))
            })
            .collect::<BTreeMap<_, _>>();
        if typedefs != version.typedefs {
            return Err(eyre!("the merged snapshot does not reproduce pg{major}'s typedefs"));
        }
        let callbacks = merged
            .callbacks
            .iter()
            .filter(|(_, versions)| versions.contains(&major))
            .map(|(path, _)| path.to_vec())
            .collect::<BTreeSet<_>>();
        if callbacks != version.callbacks {
            return Err(eyre!("the merged snapshot does not reproduce pg{major}'s callbacks"));
        }
    }
    let mut gated = BTreeMap::<&str, BTreeSet<u16>>::new();
    for ((_, identifier), variants) in &merged.macros {
        let versions = gated.entry(identifier).or_default();
        for major in variants.iter().flat_map(|variant| variant.locations.keys()) {
            if !versions.insert(*major) {
                return Err(eyre!("pg{major} gates two definitions of {identifier}"));
            }
        }
    }
    let mut defining = BTreeMap::<&str, BTreeSet<u16>>::new();
    for version in versions {
        for (_, identifier) in version.macros.keys() {
            defining.entry(identifier).or_default().insert(version.major);
        }
    }
    if gated != defining {
        return Err(eyre!("snapshot gates do not match the versions defining each macro"));
    }
    Ok(())
}

/// Render the merged snapshot as a module tree rooted at its `mod.rs`.
pub(super) fn snapshot_files(versions: &[SnapshotVersion]) -> eyre::Result<MacroFiles> {
    let merged = merge(versions)?;
    verify(versions, &merged)?;
    let all = &merged.all;
    let mut tree = Directory::default();
    for ((header, identifier), variants) in &merged.macros {
        let leaf = tree.header_mut(header)?;
        for variant in variants {
            let versions = variant.locations.keys().copied().collect::<BTreeSet<_>>();
            let location = merged_location(&variant.locations);
            let shell = variant
                .documentation
                .render_shell(location.as_deref(), &cfg_attribute(&versions, all))
                .ok_or_else(|| eyre!("documentation for {identifier} exceeds the output bound"))?;
            leaf.source.push_str(&shell);
            leaf.exports.entry(identifier.to_string()).or_default().extend(versions);
        }
    }
    let mut index = String::from(
        "// The generated C macros of every supported PostgreSQL version, reduced to their\n\
         // documentation. Each build generates the real macros from its own installation.\n",
    );
    write_classifier(&mut index, versions, all);
    write_typedefs(&mut index, &merged.typedefs, all);
    write_callbacks(&mut index, &merged.callbacks, all);
    let mut files = BTreeMap::new();
    tree.write(Path::new(""), &index, PREAMBLE, all, &mut files)?;
    Ok(MacroFiles { sources: files })
}

/// Describe where each version defines a merged macro, such as
/// `c.h:801 (PostgreSQL 15–17), c.h:806 (PostgreSQL 18)`.
fn merged_location(locations: &BTreeMap<u16, Option<&str>>) -> Option<String> {
    let mut by_location = BTreeMap::<&str, BTreeSet<u16>>::new();
    for (major, location) in locations {
        if let Some(location) = location {
            by_location.entry(location).or_default().insert(*major);
        }
    }
    let mut groups = by_location.into_iter().collect::<Vec<_>>();
    groups.sort_by_key(|(_, versions)| versions.first().copied());
    let described = groups
        .iter()
        .map(|(location, versions)| format!("{location} ({})", version_list(versions)))
        .collect::<Vec<_>>();
    (!described.is_empty()).then(|| described.join(", "))
}

/// Name PostgreSQL versions with consecutive majors collapsed into ranges.
fn version_list(versions: &BTreeSet<u16>) -> String {
    let mut ranges = Vec::<(u16, u16)>::new();
    for &major in versions {
        match ranges.last_mut() {
            Some((_, end)) if *end + 1 == major => *end = major,
            _ => ranges.push((major, major)),
        }
    }
    let ranges = ranges
        .iter()
        .map(|(start, end)| if start == end { start.to_string() } else { format!("{start}–{end}") })
        .collect::<Vec<_>>();
    format!("PostgreSQL {}", ranges.join(", "))
}

/// Keep `if_c_macro!` working by reporting each version's generated macro names.
///
/// Names generated in every version are matched first; the rest are forwarded to a
/// version-gated macro listing that version's remaining names.
fn write_classifier(index: &mut String, versions: &[SnapshotVersion], all: &BTreeSet<u16>) {
    let names = versions
        .iter()
        .map(|version| {
            let names = version.macros.keys().map(|(_, identifier)| identifier.as_str()).collect();
            (version.major, names)
        })
        .collect::<BTreeMap<u16, BTreeSet<&str>>>();
    let common = names
        .values()
        .cloned()
        .reduce(|common, names| common.intersection(&names).copied().collect())
        .unwrap_or_default();
    let arm = |index: &mut String, name: &str| {
        writeln!(index, "    (@if_available {name} {{ $($items:tt)* }}) => {{ $($items)* }};")
            .expect("String output");
    };
    index.push_str("/// Report which C macros were generated, for `if_c_macro!`.\n#[doc(hidden)]\n#[macro_export]\nmacro_rules! __pgrx_c_classify {\n");
    for name in &common {
        arm(index, name);
    }
    index.push_str("    (@if_available $name:ident { $($items:tt)* }) => {\n        $crate::__pgrx_c_classify_version!(@if_available $name { $($items)* });\n    };\n}\n");
    let mut by_names = BTreeMap::<Vec<&str>, BTreeSet<u16>>::new();
    for (major, names) in &names {
        let specific = names.difference(&common).copied().collect();
        by_names.entry(specific).or_default().insert(*major);
    }
    for (specific, majors) in by_names {
        write!(
            index,
            "{}/// Report the C macros generated only in some PostgreSQL versions.\n#[doc(hidden)]\n#[macro_export]\nmacro_rules! __pgrx_c_classify_version {{\n",
            cfg_attribute(&majors, all)
        )
        .expect("String output");
        for name in specific {
            arm(index, name);
        }
        index.push_str("    (@if_available $name:ident { $($items:tt)* }) => {};\n}\n");
    }
}

/// Publish each version's C integer typedef identities.
fn write_typedefs(
    index: &mut String,
    typedefs: &BTreeMap<&str, BTreeMap<&'static str, BTreeSet<u16>>>,
    all: &BTreeSet<u16>,
) {
    index.push_str("/// C integer identities established from each version's typedef declarations.\n#[doc(hidden)]\n#[allow(non_camel_case_types)]\npub mod __pgrx_c_types {\n");
    for (name, markers) in typedefs {
        for (marker, versions) in markers {
            write!(
                index,
                "{}/// Preserve the compiler-established rank and width of C `{name}`.\npub type r#{name} = crate::__pgrx_c_macros::{marker};\n",
                cfg_attribute(versions, all)
            )
            .expect("String output");
        }
    }
    index.push_str("}\n");
}

/// Keep callback typedef names resolvable in item signatures of documented crates.
///
/// Documentation builds have no inspected callback ABI, so each alias names one
/// uninhabited placeholder instead of an exact native function type.
fn write_callbacks(
    index: &mut String,
    callbacks: &BTreeMap<&[String], BTreeSet<u16>>,
    all: &BTreeSet<u16>,
) {
    index.push_str("/// Placeholder for callback typedef identities in documentation builds.\n#[doc(hidden)]\npub enum __pgrx_c_documentation_only {}\n/// Callback typedef names generated from each version's declarations.\n#[doc(hidden)]\npub mod __pgrx_c_callbacks {\n");
    write_callback_level(index, callbacks, all, 0);
    index.push_str("}\n");
}

/// Render one module level of callback typedef aliases.
fn write_callback_level(
    index: &mut String,
    callbacks: &BTreeMap<&[String], BTreeSet<u16>>,
    all: &BTreeSet<u16>,
    depth: usize,
) {
    let mut modules = BTreeMap::<&str, BTreeMap<&[String], BTreeSet<u16>>>::new();
    for (path, versions) in callbacks {
        if let [name] = &path[depth..] {
            let placeholder = "super::".repeat(depth + 1);
            writeln!(
                index,
                "{}pub type {name} = {placeholder}__pgrx_c_documentation_only;",
                cfg_attribute(versions, all)
            )
            .expect("String output");
        } else {
            modules.entry(path[depth].as_str()).or_default().insert(path, versions.clone());
        }
    }
    for (module, children) in modules {
        let versions = children.values().flatten().copied().collect::<BTreeSet<_>>();
        writeln!(index, "{}pub mod {module} {{", cfg_attribute(&versions, all))
            .expect("String output");
        write_callback_level(index, &children, all, depth + 1);
        index.push_str("}\n");
    }
}

/// Check merging, gating, and rendering without a PostgreSQL installation.
#[cfg(test)]
mod tests {
    use super::*;

    /// Build documentation for a one-operand macro defined at `line`.
    fn documentation(identifier: &str, body: &str, line: u32) -> MacroDocumentation {
        MacroDocumentation {
            identifier: identifier.into(),
            title: format!("C macro {identifier}"),
            location: Some(format!("example.h:{line}")),
            body: format!("\n\n```text\n#define {identifier}(x) {body}\n```"),
            forms: vec!["$x:expr $(,)?".into()],
            hidden: false,
        }
    }

    /// Build one version from `(header, documentation)` pairs.
    fn version(major: u16, macros: &[(&str, MacroDocumentation)]) -> SnapshotVersion {
        SnapshotVersion {
            major,
            macros: macros
                .iter()
                .map(|(header, doc)| ((PathBuf::from(header), doc.identifier.clone()), doc.clone()))
                .collect(),
            typedefs: BTreeMap::from([("size_t".to_owned(), "CUnsignedLong")]),
            callbacks: BTreeSet::from([vec!["tree_walker_callback".to_owned()]]),
        }
    }

    /// Checks that identical definitions share one gated shell and changed ones sit side by side.
    #[test]
    fn identical_definitions_are_shared_and_changes_are_adjacent() {
        let versions = [
            version(15, &[("utils/example.h", documentation("SAME", "(x)", 10))]),
            version(
                16,
                &[
                    ("utils/example.h", documentation("SAME", "(x)", 12)),
                    ("utils/example.h", documentation("CHANGED", "(x)", 20)),
                ],
            ),
            version(
                17,
                &[
                    ("utils/example.h", documentation("SAME", "(x)", 12)),
                    ("utils/example.h", documentation("CHANGED", "((x) + 1)", 21)),
                ],
            ),
        ];
        let files = snapshot_files(&versions).unwrap();
        let header = &files.sources[Path::new("utils/example.rs")];
        assert_eq!(header.matches("macro_rules! SAME").count(), 1);
        assert!(header.contains(
            "/// C macro SAME from example.h:10 (PostgreSQL 15), example.h:12 (PostgreSQL 16–17)"
        ));
        assert!(header.contains("#[cfg(feature = \"pg16\")]\n/// C macro CHANGED"));
        assert!(header.contains("#[cfg(feature = \"pg17\")]\n/// C macro CHANGED"));
        assert!(
            header
                .contains("#[cfg(any(feature = \"pg16\", feature = \"pg17\"))]\npub use CHANGED;")
        );
        assert!(header.contains("\npub use SAME;"));
        assert!(header.contains("($x:expr $(,)?) => {"));
        assert!(!header.contains("$crate::__pgrx_c_macros"));
        let index = &files.sources[Path::new("mod.rs")];
        assert!(index.contains("mod utils;"));
        assert!(index.contains("(@if_available SAME { $($items:tt)* })"));
        assert!(index.contains("#[cfg(feature = \"pg15\")]\n/// Report the C macros"));
        assert!(index.contains(
            "#[cfg(any(feature = \"pg16\", feature = \"pg17\"))]\n/// Report the C macros"
        ));
        assert!(index.contains("pub type r#size_t = crate::__pgrx_c_macros::CUnsignedLong;"));
        assert!(
            index.contains("pub type tree_walker_callback = super::__pgrx_c_documentation_only;")
        );
        for source in files.sources.values() {
            assert!(source.starts_with(PREAMBLE));
            syn::parse_file(source).unwrap();
        }
    }

    /// Checks that headers present in only some versions are gated as modules.
    #[test]
    fn version_specific_headers_are_gated_modules() {
        let versions = [
            version(15, &[("old.h", documentation("OLD", "(x)", 1))]),
            version(16, &[("new.h", documentation("NEW", "(x)", 1))]),
        ];
        let files = snapshot_files(&versions).unwrap();
        let index = &files.sources[Path::new("mod.rs")];
        assert!(index.contains("#[cfg(feature = \"pg15\")]\n#[path = \"old.rs\"]\nmod old;"));
        assert!(index.contains("#[cfg(feature = \"pg16\")]\n#[path = \"new.rs\"]\nmod new;"));
    }

    /// Checks that a macro moving between headers keeps disjoint gates.
    #[test]
    fn a_macro_moving_between_headers_keeps_exclusive_gates() {
        let versions = [
            version(15, &[("a.h", documentation("MOVED", "(x)", 1))]),
            version(16, &[("b.h", documentation("MOVED", "(x)", 1))]),
        ];
        let files = snapshot_files(&versions).unwrap();
        assert!(
            files.sources[Path::new("a.rs")].contains("#[cfg(feature = \"pg15\")]\npub use MOVED;")
        );
        assert!(
            files.sources[Path::new("b.rs")].contains("#[cfg(feature = \"pg16\")]\npub use MOVED;")
        );
    }

    /// Checks that version lists collapse consecutive majors.
    #[test]
    fn version_lists_collapse_ranges() {
        assert_eq!(version_list(&BTreeSet::from([15, 16, 17, 19])), "PostgreSQL 15–17, 19");
        assert_eq!(version_list(&BTreeSet::from([18])), "PostgreSQL 18");
    }

    /// Checks that duplicate versions and conflicting gates are rejected.
    #[test]
    fn inconsistent_inputs_are_rejected() {
        let versions = [
            version(15, &[("a.h", documentation("X", "(x)", 1))]),
            version(15, &[("a.h", documentation("X", "(x)", 1))]),
        ];
        assert!(snapshot_files(&versions).is_err());
        let mut broken = version(16, &[("a.h", documentation("X", "(x)", 1))]);
        broken.macros.insert((PathBuf::from("b.h"), "X".into()), documentation("X", "(x)", 2));
        assert!(snapshot_files(&[broken]).is_err());
    }
}
