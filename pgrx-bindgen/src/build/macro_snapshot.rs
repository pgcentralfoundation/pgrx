    /// A witness naming `field`'s generated marker, as a member macro's shell does.
    fn witness(field: &str) -> DocumentedResult {
        DocumentedResult::Value {
            witness: format!(
                "{{ $crate::__pgrx_c_macros::expression::load($crate::__pgrx_c_macros::expression::project::<$crate::__pgrx_c_generated::{field}, _, _>($crate::__pgrx_c_operand!(@value [true]; (@native [$x])))) }}"
            ),
        }
    }

    /// Build documentation for a one-operand macro defined at `line`.
    fn documentation(identifier: &str, body: &str, line: u32) -> MacroDocumentation {
        MacroDocumentation {
            identifier: identifier.into(),
            title: format!("C macro {identifier}"),
            location: Some(format!("example.h:{line}")),
            body: format!("\n\n```text\n#define {identifier}(x) {body}\n```"),
            forms: vec!["$x:expr $(,)?".into()],
            hidden: false,
            result: witness("Field_value"),
        }
    }

    /// Generated support shared by the fixture versions, followed by `extra`.
    fn support(extra: &str) -> String {
        format!(
            "#[doc(hidden)]\n#[macro_export]\nmacro_rules! __pgrx_c_classify {{ (@if_available $name:ident {{ $($items:tt)* }}) => {{}}; }}\n\
             #[doc(hidden)]\n#[macro_export]\nmacro_rules! __pgrx_c_operand {{ ($($tokens:tt)*) => {{ () }}; }}\n\
             /// C integer identities.\n#[doc(hidden)]\npub mod __pgrx_c_types {{\npub type r#size_t = crate::__pgrx_c_macros::CUnsignedLong;\n}}\n\
             #[doc(hidden)]\npub mod __pgrx_c_generated {{\nuse crate::__pgrx_c_macros as c;\npub enum Field_value {{}}\n// SAFETY: the fixture's assertion.\nconst _: () = assert!(true);\n{extra}}}\n"
        )
    }

    /// Build one version from `(header, documentation)` pairs and its support.
    fn version(
        major: u16,
        macros: &[(&str, MacroDocumentation)],
        support: String,
    ) -> SnapshotVersion {
        SnapshotVersion {
            major,
            macros: macros
                .iter()
                .map(|(header, doc)| ((PathBuf::from(header), doc.identifier.clone()), doc.clone()))
                .collect(),
            support,
            generation: format!("{major:064x}"),
        }
    }

    /// The concatenated sources of every support fragment.
    fn support_source(files: &MacroFiles) -> String {
        files
            .sources
            .iter()
            .filter(|(path, _)| path.starts_with("__pgrx_c_support"))
            .map(|(_, source)| source.as_str())
            .collect()
    }

    /// Checks that identical definitions share one gated shell and changed ones sit side by side.
    #[test]
    fn identical_definitions_are_shared_and_changes_are_adjacent() {
        let versions = [
            version(15, &[("utils/example.h", documentation("SAME", "(x)", 10))], support("")),
            version(
                16,
                &[
                    ("utils/example.h", documentation("SAME", "(x)", 12)),
                    ("utils/example.h", documentation("CHANGED", "(x)", 20)),
                ],
                support(""),
            ),
            version(
                17,
                &[
                    ("utils/example.h", documentation("SAME", "(x)", 12)),
                    ("utils/example.h", documentation("CHANGED", "((x) + 1)", 21)),
                ],
                support(""),
            ),
        ];
        let files = snapshot_files(&versions, &[15, 16, 17]).unwrap();
        let header = &files.sources[Path::new("utils/example.rs")];
        assert_eq!(header.matches("macro_rules! SAME").count(), 1);
        assert!(header.contains(
            "/// C macro SAME from example.h:10 (PostgreSQL 15), example.h:12 (PostgreSQL 16–17)"
        ));
        assert!(header.contains("#[cfg(feature = \"pg16\")]\n/// C macro CHANGED"));
        assert!(header.contains("#[cfg(feature = \"pg17\")]\n/// C macro CHANGED"));
        assert!(
            header
                .contains("#[cfg(any(feature = \"pg16\", feature = \"pg17\"))]\npub use CHANGED;")
        );
        assert!(header.contains("\npub use SAME;"));
        assert!(header.contains("$crate::__pgrx_c_documentation_shell!(\n            @value {"));
        assert!(header.contains("$crate::__pgrx_c_generated::Field_value"));
        assert!(!header.contains("unimplemented"));
        let index = &files.sources[Path::new("mod.rs")];
        assert!(index.contains("mod utils;"));
        assert_eq!(index.matches("macro_rules! __pgrx_c_documentation_shell").count(), 1);
        assert!(index.contains("(@if_available SAME { $($items:tt)* })"));
        assert!(index.contains("#[cfg(feature = \"pg15\")]\n/// Report the C macros"));
        assert!(index.contains(
            "#[cfg(any(feature = \"pg16\", feature = \"pg17\"))]\n/// Report the C macros"
        ));
        assert!(index.contains("include!(\"__pgrx_c_support/shared_0000.rs\");"));
        let support = support_source(&files);
        assert!(support.contains("pub type r#size_t = crate::__pgrx_c_macros::CUnsignedLong;"));
        assert!(support.contains("pub enum Field_value {}"));
        assert!(
            support.contains("// SAFETY: the fixture's assertion.\nconst _: () = assert!(true);")
        );
        // Items equal in every version need no gate, and the support's own classifier
        // gives way to the merged one in the index.
        assert!(!support.contains("#[cfg("));
        assert!(!support.contains("__pgrx_c_classify"));
        assert_eq!(
            files
                .sources
                .values()
                .map(|source| source.matches("macro_rules! __pgrx_c_classify ").count())
                .sum::<usize>(),
            1
        );
        for source in files.sources.values() {
            assert!(source.starts_with(PREAMBLE) || source.starts_with("// Shared generated"));
            syn::parse_file(source).unwrap();
        }
    }

