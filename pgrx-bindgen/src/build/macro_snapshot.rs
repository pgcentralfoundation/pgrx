//! Publish one documentation snapshot covering every supported PostgreSQL version.
//!
//! docs.rs builds pgrx-pg-sys without PostgreSQL or Clang, so release generation
//! stores the interface of each version's generated C macros: a typed documentation
//! shell for each macro, and the exact Rust support that version's ordinary build
//! includes. Shells keep each macro's documentation, invocation forms and result
//! type; macro bodies, argument normalizers and native C support stay out.
//!
//! A shell or support item that is identical in several versions is written once and
//! gated to those versions with `cfg(any(feature = ...))`. Different versions of one
//! macro sit next to each other in its header's module. Before rendering, selecting
//! each version from the merged snapshot must reproduce exactly that version's macros
//! and support items, and every support item a shell names must be defined by each
//! version the shell is gated to.

use super::macro_files::{
    Directory, HeaderPaths, MacroFiles, SupportItem, cfg_attribute, partition_support,
    support_items,
};
use eyre::eyre;
use pgrx_c_macros::{DocumentedResult, EmissionStatus, MacroDocumentation, MacroEmission};
use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::fmt::Write;
use std::path::{Path, PathBuf};

/// Comment starting every snapshot file.
const PREAMBLE: &str =
    "// Automatically generated by pgrx-c-macros for documentation. Do not hand-edit.\n";
/// The availability classifier in each version's support. The snapshot writes one
/// merged classifier instead, and two exported definitions would collide.
const CLASSIFIER: &str = "__pgrx_c_classify";

/// One PostgreSQL version's documentation-facing generated output.
pub(super) struct SnapshotVersion {
    /// PostgreSQL major version, matching its `pgNN` feature.
    major: u16,
    /// Public macro documentation keyed by defining header and Rust identifier.
    macros: BTreeMap<(PathBuf, String), MacroDocumentation>,
    /// The Rust support this version's ordinary build includes with its macros.
    support: String,
    /// The release generation id, also written to this version's bindings.
    generation: String,
}

/// Collect one version's documentation from its emitted macros.
impl SnapshotVersion {
    /// Record each emitted macro under its header relative to `header_root`, with the
    /// Rust support generated alongside them.
    pub(super) fn new(
        major: u16,
        emissions: &[MacroEmission],
        header_root: &Path,
        support: String,
    ) -> eyre::Result<Self> {
        let mut headers = HeaderPaths::new(header_root);
        let mut macros = BTreeMap::new();
        let mut identifiers = BTreeSet::new();
        for emission in emissions {
            let EmissionStatus::Emitted { documentation, .. } = &emission.status else {
                continue;
            };
            if !identifiers.insert(documentation.identifier.clone()) {
                return Err(eyre!(
                    "pg{major} generated macro identifier {} occurs more than once",
                    documentation.identifier
                ));
            }
            let header = headers.relative(&emission.analysis)?;
            macros.insert((header, documentation.identifier.clone()), (**documentation).clone());
        }
        Ok(Self { major, macros, support, generation: String::new() })
    }

    /// Record the release generation that produced this version's bindings.
    pub(super) fn generated_by(&mut self, generation: String) {
        self.generation = generation;
    }

    /// PostgreSQL major version, matching its `pgNN` feature.
    pub(super) fn major(&self) -> u16 {
        self.major
    }

    /// Summarize this version's shell results for the release report.
    ///
    /// Untyped shells keep the `!` placeholder; up to 20 of them are named.
    pub(super) fn report(&self) -> String {
        let (mut value, mut unit, mut diverges) = (0, 0, 0);
        let mut untyped = Vec::new();
        for documentation in self.macros.values() {
            match &documentation.result {
                DocumentedResult::Value { .. } => value += 1,
                DocumentedResult::Unit { .. } => unit += 1,
                DocumentedResult::Diverges => diverges += 1,
                DocumentedResult::Untyped { .. } => untyped.push(documentation.identifier.as_str()),
            }
        }
        let mut report = format!(
            "pg{} documentation shells: {value} value, {unit} unit, {diverges} diverging, {} untyped",
            self.major,
            untyped.len()
        );
        if !untyped.is_empty() {
            write!(report, " ({}", untyped[..untyped.len().min(20)].join(", "))
                .expect("String output");
            if untyped.len() > 20 {
                write!(report, ", and {} more", untyped.len() - 20).expect("String output");
            }
            report.push(')');
        }
        report
    }
}

/// One macro definition shared by several versions.
struct Variant<'a> {
    /// Documentation of the first version defining it; others differ at most in location.
    documentation: &'a MacroDocumentation,
    /// Defining location in each version that has this definition.
    locations: BTreeMap<u16, Option<&'a str>>,
}

/// All versions merged into one header tree.
struct Merged<'a> {
    /// Every version in the snapshot.
    all: BTreeSet<u16>,
    /// Definitions of each macro in each header, ordered by their first version.
    macros: BTreeMap<(&'a Path, &'a str), Vec<Variant<'a>>>,
    /// Every version's support items, merged by module.
    support: SupportModule<'a>,
}

/// Compare everything except the defining location.
fn same_definition(left: &MacroDocumentation, right: &MacroDocumentation) -> bool {
    left.identifier == right.identifier
        && left.title == right.title
        && left.body == right.body
        && left.forms == right.forms
        && left.hidden == right.hidden
        && left.result == right.result
}

/// Merge identical definitions across versions, keeping per-version locations.
fn merge<'a>(
    versions: &'a [SnapshotVersion],
    support: &'a [Vec<SupportItem<'a>>],
) -> eyre::Result<Merged<'a>> {
    let all = versions.iter().map(|version| version.major).collect::<BTreeSet<_>>();
    if all.len() != versions.len() {
        return Err(eyre!("a PostgreSQL version occurs more than once in the snapshot"));
    }
    let mut merged = Merged { all, macros: BTreeMap::new(), support: SupportModule::default() };
    for (version, items) in versions.iter().zip(support) {
        for ((header, identifier), documentation) in &version.macros {
            let variants =
                merged.macros.entry((header.as_path(), identifier.as_str())).or_default();
            let location = documentation.location.as_deref();
            match variants
                .iter_mut()
                .find(|variant| same_definition(variant.documentation, documentation))
            {
                Some(variant) => {
                    variant.locations.insert(version.major, location);
                }
                None => variants.push(Variant {
                    documentation,
                    locations: BTreeMap::from([(version.major, location)]),
                }),
            }
        }
        merged.support.merge(version.major, items, true)?;
    }
    Ok(merged)
}

/// One module's support items from every version, in first-seen order.
#[derive(Default)]
struct SupportModule<'a> {
    /// Items and nested modules in the order some version first declared them.
    entries: Vec<SupportEntry<'a>>,
    /// Entry index of each item, keyed by its trimmed text and occurrence number.
    items: HashMap<(&'a str, usize), usize>,
    /// Entry index of each nested module, keyed by name.
    modules: HashMap<&'a str, usize>,
}

/// One merged support item or nested module and the versions declaring it.
enum SupportEntry<'a> {
    /// An item whose trimmed text is identical in `versions`.
    Item {
        /// The item's trimmed source, with its leading comments.
        text: &'a str,
        /// The versions declaring this exact item.
        versions: BTreeSet<u16>,
    },
    /// A module whose declaration is identical in `versions`.
    Module {
        /// The module's identifier.
        name: &'a str,
        /// Trimmed attributes and declaration through the opening brace.
        open: &'a str,
        /// Trimmed text after the last item, through the closing brace.
        close: &'a str,
        /// The versions declaring this module.
        versions: BTreeSet<u16>,
        /// The module's merged items.
        module: SupportModule<'a>,
    },
}

/// Merge versions' support items and render them as one gated source.
impl<'a> SupportModule<'a> {
    /// Add `major`'s items of this module.
    ///
    /// An item is identified by its text and how many identical items precede it in
    /// this version's module, so items a version repeats are kept. A nested module is
    /// identified by name and must be declared identically in every version.
    fn merge(&mut self, major: u16, items: &'a [SupportItem<'a>], root: bool) -> eyre::Result<()> {
        let mut occurrences = HashMap::<&str, usize>::new();
        for item in items {
            match item {
                SupportItem::Item { text, macro_name, .. } => {
                    let text = text.trim();
                    if text.is_empty() || (root && macro_name.as_deref() == Some(CLASSIFIER)) {
                        continue;
                    }
                    let occurrence = occurrences.entry(text).or_default();
                    let key = (text, *occurrence);
                    *occurrence += 1;
                    match self.items.get(&key) {
                        Some(&index) => {
                            let SupportEntry::Item { versions, .. } = &mut self.entries[index]
                            else {
                                unreachable!("item keys index item entries")
                            };
                            versions.insert(major);
                        }
                        None => {
                            self.items.insert(key, self.entries.len());
                            self.entries.push(SupportEntry::Item {
                                text,
                                versions: BTreeSet::from([major]),
                            });
                        }
                    }
                }
                SupportItem::Module { name, open, items, close, .. } => {
                    let (open, close) = (open.trim(), close.trim());
                    let index = *self.modules.entry(name).or_insert_with(|| {
                        self.entries.push(SupportEntry::Module {
                            name,
                            open,
                            close,
                            versions: BTreeSet::new(),
                            module: SupportModule::default(),
                        });
                        self.entries.len() - 1
                    });
                    let SupportEntry::Module {
                        open: first_open,
                        close: first_close,
                        versions,
                        module,
                        ..
                    } = &mut self.entries[index]
                    else {
                        unreachable!("module keys index module entries")
                    };
                    if let Some(first) = versions.first()
                        && (*first_open != open || *first_close != close)
                    {
                        return Err(eyre!(
                            "pg{first} and pg{major} declare support module {name} differently"
                        ));
                    }
                    versions.insert(major);
                    module.merge(major, items, false)?;
                }
            }
        }
        Ok(())
    }

    /// Render this module's entries, gating each one to its versions within `scope`,
    /// the versions declaring the enclosing module.
    fn render(&self, scope: &BTreeSet<u16>, rust: &mut String) {
        for entry in &self.entries {
            match entry {
                SupportEntry::Item { text, versions } => {
                    rust.push_str(&cfg_attribute(versions, scope));
                    rust.push_str(text);
                    rust.push('\n');
                }
                SupportEntry::Module { open, close, versions, module, .. } => {
                    rust.push_str(&cfg_attribute(versions, scope));
                    rust.push_str(open);
                    rust.push('\n');
                    module.render(versions, rust);
                    rust.push_str(close);
                    rust.push('\n');
                }
            }
        }
    }

    /// Record the items `major` selects from this module, per module path.
    fn project(&self, major: u16, path: &mut Vec<&'a str>, inventory: &mut Inventory<'a>) {
        inventory.entry(path.clone()).or_default();
        for entry in &self.entries {
            match entry {
                SupportEntry::Item { text, versions } if versions.contains(&major) => {
                    *inventory.entry(path.clone()).or_default().entry(text).or_default() += 1;
                }
                SupportEntry::Module { name, versions, module, .. }
                    if versions.contains(&major) =>
                {
                    path.push(name);
                    module.project(major, path, inventory);
                    path.pop();
                }
                _ => {}
            }
        }
    }
}

/// The trimmed support item texts of each module path, with their counts.
type Inventory<'a> = BTreeMap<Vec<&'a str>, BTreeMap<&'a str, usize>>;

/// Record one version's own support items, as [`SupportModule::project`] does.
fn inventory<'a>(
    items: &'a [SupportItem<'a>],
    path: &mut Vec<&'a str>,
    counts: &mut Inventory<'a>,
) {
    counts.entry(path.clone()).or_default();
    for item in items {
        match item {
            SupportItem::Item { text, macro_name, .. } => {
                let text = text.trim();
                if text.is_empty() || (path.is_empty() && macro_name.as_deref() == Some(CLASSIFIER))
                {
                    continue;
                }
                *counts.entry(path.clone()).or_default().entry(text).or_default() += 1;
            }
            SupportItem::Module { name, items, .. } => {
                path.push(name);
                inventory(items, path, counts);
                path.pop();
            }
        }
    }
}

/// The support items a version defines, by the paths shells name them with.
#[derive(Default)]
struct Definitions {
    /// Items of `__pgrx_c_generated`.
    generated: BTreeSet<String>,
    /// Aliases in `__pgrx_c_types`.
    types: BTreeSet<String>,
    /// Exported macros, which `$crate::` names at the crate root.
    macros: BTreeSet<String>,
}

/// Collect the names one version's support defines.
impl Definitions {
    /// Collect names from one version's support items.
    fn new(items: &[SupportItem<'_>]) -> Self {
        let mut definitions = Self::default();
        for item in items {
            if let SupportItem::Module { name, items, .. } = item {
                let names = match name.as_str() {
                    "__pgrx_c_generated" => Some(&mut definitions.generated),
                    "__pgrx_c_types" => Some(&mut definitions.types),
                    _ => None,
                };
                if let Some(names) = names {
                    names.extend(items.iter().filter_map(|item| match item {
                        SupportItem::Item { name, .. } => name.clone(),
                        SupportItem::Module { name, .. } => Some(name.clone()),
                    }));
                }
            }
        }
        definitions.collect_macros(items);
        definitions
    }

    /// Collect macro definitions at any depth.
    fn collect_macros(&mut self, items: &[SupportItem<'_>]) {
        for item in items {
            match item {
                SupportItem::Item { macro_name: Some(name), .. } => {
                    self.macros.insert(name.clone());
                }
                SupportItem::Item { .. } => {}
                SupportItem::Module { items, .. } => self.collect_macros(items),
            }
        }
    }

    /// The first name in `source` that these definitions lack.
    ///
    /// Shells name support items as `$crate::__pgrx_c_generated::X`,
    /// `$crate::__pgrx_c_types::X` and `$crate::X!`.
    fn missing<'s>(&self, source: &'s str) -> Option<&'s str> {
        source.match_indices("$crate::").find_map(|(start, _)| {
            let rest = &source[start + "$crate::".len()..];
            let end = rest
                .find(|character: char| {
                    !(character.is_ascii_alphanumeric() || matches!(character, '_' | ':' | '#'))
                })
                .unwrap_or(rest.len());
            let path = &rest[..end];
            let mut segments = path.split("::").map(|segment| segment.trim_start_matches("r#"));
            let first = segments.next()?;
            let defined = match (first, segments.next()) {
                ("__pgrx_c_generated", Some(name)) => self.generated.contains(name),
                ("__pgrx_c_types", Some(name)) => self.types.contains(name),
                (name, None) if rest[end..].starts_with('!') => self.macros.contains(name),
                _ => true,
            };
            (!defined).then_some(path)
        })
    }
}

/// The source of a shell's arms that names support items.
fn shell_source(result: &DocumentedResult) -> &str {
    match result {
        DocumentedResult::Unit { body } => body,
        DocumentedResult::Value { witness } => witness,
        DocumentedResult::Diverges | DocumentedResult::Untyped { .. } => "",
    }
}

/// Prove the merged snapshot loses nothing and gates each name exclusively.
///
/// Selecting one version's definitions from the merged snapshot must reproduce that
/// version's macros, locations and support items. The definitions of one macro must
/// have disjoint version sets whose union is the set of versions defining it. Each
/// support item a shell names must be defined by every version the shell is gated to.
fn verify(
    versions: &[SnapshotVersion],
    support: &[Vec<SupportItem<'_>>],
    merged: &Merged<'_>,
) -> eyre::Result<()> {
    for (version, items) in versions.iter().zip(support) {
        let major = version.major;
        let mut projected = BTreeMap::new();
        for ((header, identifier), variants) in &merged.macros {
            for variant in variants {
                let Some(location) = variant.locations.get(&major) else { continue };
                let mut documentation = variant.documentation.clone();
                documentation.location = location.map(str::to_owned);
                if projected
                    .insert((header.to_path_buf(), identifier.to_string()), documentation)
                    .is_some()
                {
                    return Err(eyre!("pg{major} selects two definitions of {identifier}"));
                }
            }
        }
        if projected != version.macros {
            return Err(eyre!("the merged snapshot does not reproduce pg{major}'s macros"));
        }
        let mut expected = Inventory::new();
        inventory(items, &mut Vec::new(), &mut expected);
        let mut actual = Inventory::new();
        merged.support.project(major, &mut Vec::new(), &mut actual);
        if actual != expected {
            let module = expected
                .keys()
                .chain(actual.keys())
                .find(|path| expected.get(*path) != actual.get(*path))
                .map_or_else(|| "the crate root".to_owned(), |path| path.join("::"));
            return Err(eyre!(
                "the merged snapshot does not reproduce pg{major}'s support items in {}",
                if module.is_empty() { "the crate root" } else { &module }
            ));
        }
    }
    let mut gated = BTreeMap::<&str, BTreeSet<u16>>::new();
    for ((_, identifier), variants) in &merged.macros {
        let versions = gated.entry(identifier).or_default();
        for major in variants.iter().flat_map(|variant| variant.locations.keys()) {
            if !versions.insert(*major) {
                return Err(eyre!("pg{major} gates two definitions of {identifier}"));
            }
        }
    }
    let mut defining = BTreeMap::<&str, BTreeSet<u16>>::new();
    for version in versions {
        for (_, identifier) in version.macros.keys() {
            defining.entry(identifier).or_default().insert(version.major);
        }
    }
    if gated != defining {
        return Err(eyre!("snapshot gates do not match the versions defining each macro"));
    }
    let definitions = versions
        .iter()
        .zip(support)
        .map(|(version, items)| (version.major, Definitions::new(items)))
        .collect::<BTreeMap<_, _>>();
    for ((_, identifier), variants) in &merged.macros {
        for variant in variants {
            let source = shell_source(&variant.documentation.result);
            for major in variant.locations.keys() {
                if let Some(name) = definitions[major].missing(source) {
                    return Err(eyre!(
                        "pg{major} shell {identifier} references {name}, which pg{major}'s generated support does not define"
                    ));
                }
            }
        }
    }
    Ok(())
}

/// Render the merged snapshot as a module tree rooted at its `mod.rs`.
///
/// `supported` lists every PostgreSQL major version pgrx supports. A supported version
/// missing from `versions` fails to compile under docs builds instead of documenting
/// another version's macros.
pub(super) fn snapshot_files(
    versions: &[SnapshotVersion],
    supported: &[u16],
) -> eyre::Result<MacroFiles> {
    let support = versions
        .iter()
        .map(|version| support_items(&version.support))
        .collect::<eyre::Result<Vec<_>>>()?;
    let merged = merge(versions, &support)?;
    verify(versions, &support, &merged)?;
    let all = &merged.all;
    let mut tree = Directory::default();
    for ((header, identifier), variants) in &merged.macros {
        let leaf = tree.header_mut(header)?;
        for variant in variants {
            let versions = variant.locations.keys().copied().collect::<BTreeSet<_>>();
            let location = merged_location(&variant.locations);
            let shell = variant
                .documentation
                .render_shell(location.as_deref(), &cfg_attribute(&versions, all))
                .map_err(|message| eyre!("{identifier}: {message}"))?;
            leaf.source.push_str(&shell);
            leaf.exports.entry(identifier.to_string()).or_default().extend(versions);
        }
    }
    let mut index = String::from(
        "// The generated C macros of every supported PostgreSQL version, reduced to their\n\
         // documented interface: typed shells and the Rust support each build generates.\n",
    );
    index.push_str(&pgrx_c_macros::documentation_shell_support());
    write_classifier(&mut index, versions, all);
    for version in versions {
        let major = version.major;
        write!(
            index,
            "{}const _: () = ::core::assert!(\n    ::core::matches!(crate::__pgrx_c_bindings::__PGRX_GENERATION.as_bytes(), b{:?}),\n    \"the documentation snapshot and src/include/pg{major}.rs come from different release generations; regenerate them together\"\n);\n",
            cfg_attribute(&BTreeSet::from([major]), &BTreeSet::new()),
            version.generation,
        )
        .expect("String output");
    }
    for major in supported.iter().filter(|major| !all.contains(major)) {
        write!(
            index,
            "#[cfg(feature = \"pg{major}\")]\n::core::compile_error!(\"the C macro documentation snapshot does not include pg{major}; regenerate it with every supported PostgreSQL version configured\");\n"
        )
        .expect("String output");
    }
    let mut source = String::new();
    merged.support.render(all, &mut source);
    let mut files = BTreeMap::new();
    for fragment in partition_support(&source, &mut files)? {
        writeln!(
            index,
            "include!({:?});",
            fragment.to_str().ok_or_else(|| eyre!("support fragment path is not UTF-8"))?
        )
        .expect("String output");
    }
    tree.write(Path::new(""), &index, PREAMBLE, all, &mut files)?;
    Ok(MacroFiles { sources: files })
}

/// Describe where each version defines a merged macro, such as
/// `c.h:801 (PostgreSQL 15–17), c.h:806 (PostgreSQL 18)`.
fn merged_location(locations: &BTreeMap<u16, Option<&str>>) -> Option<String> {
    let mut by_location = BTreeMap::<&str, BTreeSet<u16>>::new();
    for (major, location) in locations {
        if let Some(location) = location {
            by_location.entry(location).or_default().insert(*major);
        }
    }
    let mut groups = by_location.into_iter().collect::<Vec<_>>();
    groups.sort_by_key(|(_, versions)| versions.first().copied());
    let described = groups
        .iter()
        .map(|(location, versions)| format!("{location} ({})", version_list(versions)))
        .collect::<Vec<_>>();
    (!described.is_empty()).then(|| described.join(", "))
}

/// Name PostgreSQL versions with consecutive majors collapsed into ranges.
fn version_list(versions: &BTreeSet<u16>) -> String {
    let mut ranges = Vec::<(u16, u16)>::new();
    for &major in versions {
        match ranges.last_mut() {
            Some((_, end)) if *end + 1 == major => *end = major,
            _ => ranges.push((major, major)),
        }
    }
    let ranges = ranges
        .iter()
        .map(|(start, end)| if start == end { start.to_string() } else { format!("{start}–{end}") })
        .collect::<Vec<_>>();
    format!("PostgreSQL {}", ranges.join(", "))
}

/// Keep `if_c_macro!` working by reporting each version's generated macro names.
///
/// Names generated in every version are matched first; the rest are forwarded to a
/// version-gated macro listing that version's remaining names.
fn write_classifier(index: &mut String, versions: &[SnapshotVersion], all: &BTreeSet<u16>) {
    let names = versions
        .iter()
        .map(|version| {
            let names = version.macros.keys().map(|(_, identifier)| identifier.as_str()).collect();
            (version.major, names)
        })
        .collect::<BTreeMap<u16, BTreeSet<&str>>>();
    let common = names
        .values()
        .cloned()
        .reduce(|common, names| common.intersection(&names).copied().collect())
        .unwrap_or_default();
    let arm = |index: &mut String, name: &str| {
        writeln!(index, "    (@if_available {name} {{ $($items:tt)* }}) => {{ $($items)* }};")
            .expect("String output");
    };
    index.push_str("/// Report which C macros were generated, for `if_c_macro!`.\n#[doc(hidden)]\n#[macro_export]\nmacro_rules! __pgrx_c_classify {\n");
    for name in &common {
        arm(index, name);
    }
    index.push_str("    (@if_available $name:ident { $($items:tt)* }) => {\n        $crate::__pgrx_c_classify_version!(@if_available $name { $($items)* });\n    };\n}\n");
    let mut by_names = BTreeMap::<Vec<&str>, BTreeSet<u16>>::new();
    for (major, names) in &names {
        let specific = names.difference(&common).copied().collect();
        by_names.entry(specific).or_default().insert(*major);
    }
    for (specific, majors) in by_names {
        write!(
            index,
            "{}/// Report the C macros generated only in some PostgreSQL versions.\n#[doc(hidden)]\n#[macro_export]\nmacro_rules! __pgrx_c_classify_version {{\n",
            cfg_attribute(&majors, all)
        )
        .expect("String output");
        for name in specific {
            arm(index, name);
        }
        index.push_str("    (@if_available $name:ident { $($items:tt)* }) => {};\n}\n");
    }
}

