//! SQL upgrade script generation from schema diffs.
//!
//! This module takes a SchemaDiff and generates PostgreSQL SQL statements
//! to upgrade from one version to another.

use crate::SqlGraphIdentifier;
use crate::diff::{EntityChange, EntityModification, EntityRename, SchemaDiff};
use crate::metadata::SqlMapping;
use crate::pg_extern::entity::PgExternEntity;
use crate::pgrx_sql::PgrxSql;
use crate::snapshot_types::SqlGraphEntitySnapshot;
use crate::to_sql::ToSql;
use std::fmt::Write as FmtWrite;

type Result<T> = std::result::Result<T, std::fmt::Error>;

/// Generate the argument type list from metadata only (for removed functions).
/// This doesn't require the PgrxSql context, so it works for entities that no longer exist.
fn generate_function_arg_types_from_metadata(func: &PgExternEntity) -> String {
    if func.fn_args.is_empty() {
        return String::new();
    }

    let mut arg_types = Vec::new();

    for (idx, _arg) in func.fn_args.iter().enumerate() {
        let metadata_argument = &func.metadata.arguments[idx];

        // Skip arguments that don't appear in SQL
        if metadata_argument.argument_sql == Ok(SqlMapping::Skip) {
            continue;
        }

        let type_name = match &metadata_argument.argument_sql {
            Ok(SqlMapping::As(sql)) => sql.clone(),
            Ok(SqlMapping::Composite { .. }) => {
                // For composite types, we'd need the context to get the full type name
                // Just use the type name from metadata
                metadata_argument.type_name.to_string()
            }
            Ok(SqlMapping::Skip) => continue,
            Err(_) => {
                // If we can't get the type, skip it with a comment
                continue;
            }
        };

        arg_types.push(type_name);
    }

    arg_types.join(", ")
}

/// Configuration for upgrade script generation.
#[derive(Debug, Clone)]
pub struct UpgradeConfig {
    /// Whether to include safety comments
    pub include_comments: bool,
    /// Whether to wrap the script in a transaction
    pub use_transaction: bool,
    /// Whether to generate IF EXISTS/IF NOT EXISTS clauses
    pub use_conditional_clauses: bool,
    /// Whether to generate manual review markers for risky changes
    pub mark_manual_review: bool,
}

impl Default for UpgradeConfig {
    fn default() -> Self {
        Self {
            include_comments: true,
            use_transaction: false, // Transactions don't work well with DDL in all cases
            use_conditional_clauses: true,
            mark_manual_review: true,
        }
    }
}

/// Generate an upgrade script from a schema diff.
pub fn generate_upgrade_script(diff: &SchemaDiff, config: &UpgradeConfig) -> Result<String> {
    let mut script = String::new();

    // Header
    if config.include_comments {
        writeln!(
            &mut script,
            "-- Upgrade script from version {} to {}",
            diff.from_version, diff.to_version
        )?;
        writeln!(&mut script, "-- Generated by pgrx automatic upgrade script generator")?;
        writeln!(&mut script, "--")?;
        writeln!(&mut script, "-- Summary: {}", diff.summary())?;
        writeln!(&mut script)?;

        if diff.has_breaking_changes() {
            writeln!(&mut script, "-- WARNING: This upgrade contains breaking changes!")?;
            writeln!(&mut script, "-- Review carefully before applying to production.")?;
            writeln!(&mut script)?;
        }
    }

    // Transaction begin
    if config.use_transaction {
        writeln!(&mut script, "BEGIN;")?;
        writeln!(&mut script)?;
    }

    // Process renames first (they're the trickiest)
    if !diff.renamed.is_empty() {
        if config.include_comments {
            writeln!(&mut script, "-- Renamed entities")?;
        }
        for rename in &diff.renamed {
            generate_rename_statement(&mut script, rename, config)?;
        }
        writeln!(&mut script)?;
    }

    // Process removals (in reverse dependency order)
    if !diff.removed.is_empty() {
        if config.include_comments {
            writeln!(&mut script, "-- Removed entities")?;
        }
        let removals = diff.removals_in_dependency_order();
        for removal in removals {
            generate_drop_statement(&mut script, removal, config)?;
        }
        writeln!(&mut script)?;
    }

    // Process modifications
    if !diff.modified.is_empty() {
        if config.include_comments {
            writeln!(&mut script, "-- Modified entities")?;
        }
        for modification in &diff.modified {
            generate_modify_statement(&mut script, modification, config)?;
        }
        writeln!(&mut script)?;
    }

    // Process additions (in dependency order)
    if !diff.added.is_empty() {
        if config.include_comments {
            writeln!(&mut script, "-- Added entities")?;
        }
        let additions = diff.additions_in_dependency_order();
        for addition in additions {
            generate_create_statement(&mut script, addition, config)?;
        }
        writeln!(&mut script)?;
    }

    // Transaction end
    if config.use_transaction {
        writeln!(&mut script, "COMMIT;")?;
    }

    Ok(script)
}

/// Generate a DROP statement for a removed entity.
fn generate_drop_statement(
    script: &mut String,
    change: &EntityChange,
    config: &UpgradeConfig,
) -> Result<()> {
    if config.include_comments {
        writeln!(script, "-- Drop: {}", change.id.rust_identifier)?;
        if let (Some(file), Some(line)) = (change.entity.file(), change.entity.line()) {
            writeln!(script, "-- Source: {}:{}", file, line)?;
        }
    }

    match &change.entity {
        SqlGraphEntitySnapshot::Function(func) => {
            let if_exists = if config.use_conditional_clauses { "IF EXISTS " } else { "" };

            writeln!(script, "DROP FUNCTION {}{}(...);", if_exists, func.name)?;

            if config.mark_manual_review {
                writeln!(
                    script,
                    "-- MANUAL REVIEW: Verify function signature matches: {}",
                    change.id.rust_identifier
                )?;
            }
        }
        SqlGraphEntitySnapshot::Type(pg_type) => {
            let if_exists = if config.use_conditional_clauses { "IF EXISTS " } else { "" };
            writeln!(script, "DROP TYPE {}{} CASCADE;", if_exists, pg_type.name)?;

            if config.mark_manual_review {
                writeln!(script, "-- MANUAL REVIEW: CASCADE may drop dependent objects")?;
            }
        }
        SqlGraphEntitySnapshot::Enum(enum_entity) => {
            let if_exists = if config.use_conditional_clauses { "IF EXISTS " } else { "" };
            writeln!(script, "DROP TYPE {}{} CASCADE;", if_exists, enum_entity.name)?;
        }
        SqlGraphEntitySnapshot::Schema(schema) => {
            let if_exists = if config.use_conditional_clauses { "IF EXISTS " } else { "" };
            writeln!(script, "DROP SCHEMA {}{} CASCADE;", if_exists, schema.name)?;

            if config.mark_manual_review {
                writeln!(script, "-- MANUAL REVIEW: CASCADE will drop all objects in schema")?;
            }
        }
        SqlGraphEntitySnapshot::Aggregate(agg) => {
            let if_exists = if config.use_conditional_clauses { "IF EXISTS " } else { "" };
            writeln!(script, "DROP AGGREGATE {}{}(...);", if_exists, agg.name)?;

            if config.mark_manual_review {
                writeln!(script, "-- MANUAL REVIEW: Verify aggregate signature")?;
            }
        }
        SqlGraphEntitySnapshot::Trigger(trigger) => {
            if config.mark_manual_review {
                writeln!(
                    script,
                    "-- MANUAL REVIEW: Need table name to drop trigger: {}",
                    trigger.function_name
                )?;
            }
            writeln!(script, "-- DROP TRIGGER {} ON <table_name>;", trigger.function_name)?;
        }
        _ => {
            writeln!(script, "-- Unable to generate DROP for: {}", change.id.rust_identifier)?;
        }
    }

    writeln!(script)?;
    Ok(())
}

/// Generate a CREATE statement for a new entity.
fn generate_create_statement(
    script: &mut String,
    change: &EntityChange,
    config: &UpgradeConfig,
) -> Result<()> {
    if config.include_comments {
        writeln!(script, "-- Create: {}", change.id.rust_identifier)?;
        if let (Some(file), Some(line)) = (change.entity.file(), change.entity.line()) {
            writeln!(script, "-- Source: {}:{}", file, line)?;
        }
    }

    match &change.entity {
        SqlGraphEntitySnapshot::Schema(schema) => {
            writeln!(script, "CREATE SCHEMA IF NOT EXISTS {};", schema.name)?;
        }
        SqlGraphEntitySnapshot::Enum(enum_entity) => {
            writeln!(script, "CREATE TYPE {} AS ENUM (", enum_entity.name)?;
            for (i, variant) in enum_entity.variants.iter().enumerate() {
                let comma = if i < enum_entity.variants.len() - 1 { "," } else { "" };
                writeln!(script, "    '{}'{}", variant, comma)?;
            }
            writeln!(script, ");")?;
        }
        SqlGraphEntitySnapshot::Function(_)
        | SqlGraphEntitySnapshot::Type(_)
        | SqlGraphEntitySnapshot::Aggregate(_) => {
            writeln!(
                script,
                "-- CREATE statement for {} must be generated from full context",
                change.id.rust_identifier
            )?;
            if config.mark_manual_review {
                writeln!(
                    script,
                    "-- MANUAL REVIEW: Add complete CREATE statement for this entity"
                )?;
            }
        }
        _ => {
            writeln!(script, "-- Unable to generate CREATE for: {}", change.id.rust_identifier)?;
        }
    }

    writeln!(script)?;
    Ok(())
}

/// Generate an ALTER or DROP/CREATE for a modified entity.
fn generate_modify_statement(
    script: &mut String,
    modification: &EntityModification,
    config: &UpgradeConfig,
) -> Result<()> {
    if config.include_comments {
        writeln!(script, "-- Modify: {}", modification.id.rust_identifier)?;
        if let (Some(file), Some(line)) =
            (modification.new_entity.file(), modification.new_entity.line())
        {
            writeln!(script, "-- Source: {}:{}", file, line)?;
        }
        writeln!(script, "-- Changes:")?;
        for change in &modification.changes {
            writeln!(script, "--   - {}", change)?;
        }
    }

    match (&modification.old_entity, &modification.new_entity) {
        (SqlGraphEntitySnapshot::Function(_), SqlGraphEntitySnapshot::Function(new_func)) => {
            // Functions typically need CREATE OR REPLACE
            writeln!(script, "-- CREATE OR REPLACE FUNCTION {} ...", new_func.name)?;
            if config.mark_manual_review {
                writeln!(script, "-- MANUAL REVIEW: Generate complete function definition")?;
            }
        }
        (SqlGraphEntitySnapshot::Enum(old_enum), SqlGraphEntitySnapshot::Enum(new_enum)) => {
            // Enums are tricky - can only add values in PostgreSQL
            let old_variants: std::collections::HashSet<_> = old_enum.variants.iter().collect();
            let new_variants: std::collections::HashSet<_> = new_enum.variants.iter().collect();

            // Check for added variants
            for variant in &new_enum.variants {
                if !old_variants.contains(variant) {
                    writeln!(
                        script,
                        "ALTER TYPE {} ADD VALUE IF NOT EXISTS '{}';",
                        new_enum.name, variant
                    )?;
                }
            }

            // Check for removed variants
            for variant in &old_enum.variants {
                if !new_variants.contains(variant) && config.mark_manual_review {
                    writeln!(
                        script,
                        "-- MANUAL REVIEW: Cannot remove enum value '{}' from {} - requires type recreation",
                        variant, old_enum.name
                    )?;
                }
            }
        }
        (SqlGraphEntitySnapshot::Type(_old_type), SqlGraphEntitySnapshot::Type(new_type)) => {
            // Types usually need to be dropped and recreated
            writeln!(
                script,
                "-- Type {} was modified - may require DROP and recreate",
                new_type.name
            )?;
            if config.mark_manual_review {
                writeln!(
                    script,
                    "-- MANUAL REVIEW: Type modifications often require data migration"
                )?;
            }
        }
        _ => {
            writeln!(
                script,
                "-- Unable to generate ALTER for: {}",
                modification.id.rust_identifier
            )?;
        }
    }

    writeln!(script)?;
    Ok(())
}

/// Generate RENAME or DROP/CREATE for a renamed entity.
fn generate_rename_statement(
    script: &mut String,
    rename: &EntityRename,
    config: &UpgradeConfig,
) -> Result<()> {
    if config.include_comments {
        writeln!(
            script,
            "-- Rename: {} -> {} (confidence: {:.0}%)",
            rename.old_id.rust_identifier,
            rename.new_id.rust_identifier,
            rename.confidence * 100.0
        )?;
    }

    if config.mark_manual_review {
        writeln!(script, "-- MANUAL REVIEW: Verify this rename is correct")?;
    }

    match (&rename.old_entity, &rename.new_entity) {
        (SqlGraphEntitySnapshot::Function(old_fn), SqlGraphEntitySnapshot::Function(new_fn)) => {
            writeln!(script, "-- ALTER FUNCTION {}(...) RENAME TO {};", old_fn.name, new_fn.name)?;
            writeln!(script, "-- Note: Function signature must match exactly")?;
        }
        (SqlGraphEntitySnapshot::Type(old_type), SqlGraphEntitySnapshot::Type(new_type)) => {
            writeln!(script, "ALTER TYPE {} RENAME TO {};", old_type.name, new_type.name)?;
        }
        (SqlGraphEntitySnapshot::Enum(old_enum), SqlGraphEntitySnapshot::Enum(new_enum)) => {
            writeln!(script, "ALTER TYPE {} RENAME TO {};", old_enum.name, new_enum.name)?;
        }
        (
            SqlGraphEntitySnapshot::Schema(old_schema),
            SqlGraphEntitySnapshot::Schema(new_schema),
        ) => {
            writeln!(script, "ALTER SCHEMA {} RENAME TO {};", old_schema.name, new_schema.name)?;
        }
        _ => {
            writeln!(
                script,
                "-- Unable to generate RENAME for: {} -> {}",
                rename.old_id.rust_identifier, rename.new_id.rust_identifier
            )?;
        }
    }

    writeln!(script)?;
    Ok(())
}

/// Generate a complete upgrade script file with proper header and footer.
pub fn generate_upgrade_file(
    from_version: &str,
    to_version: &str,
    diff: &SchemaDiff,
    config: &UpgradeConfig,
) -> Result<String> {
    let mut output = String::new();

    // Extension upgrade file header
    writeln!(
        &mut output,
        "-- Upgrade script for extension from {} to {}",
        from_version, to_version
    )?;
    writeln!(&mut output)?;

    // Generate the script content
    let script = generate_upgrade_script(diff, config)?;
    output.push_str(&script);

    Ok(output)
}

/// Generate an upgrade script with actual SQL using the PgrxSql context.
///
/// This version can generate complete CREATE statements for functions, types, etc.
/// by using the ToSql trait implementations.
pub fn generate_upgrade_script_with_sql(
    from_version: &str,
    to_version: &str,
    diff: &SchemaDiff,
    pgrx_sql: &PgrxSql,
) -> eyre::Result<String> {
    let mut script = String::new();

    // Header
    writeln!(
        &mut script,
        "-- Upgrade script for extension from {} to {}",
        from_version, to_version
    )
    .map_err(|e| eyre::eyre!("Failed to write header: {}", e))?;
    writeln!(&mut script, "-- Generated by pgrx automatic upgrade script generator")
        .map_err(|e| eyre::eyre!("Failed to write header: {}", e))?;
    writeln!(&mut script, "--").map_err(|e| eyre::eyre!("Failed to write header: {}", e))?;
    writeln!(&mut script, "-- Summary: {}", diff.summary())
        .map_err(|e| eyre::eyre!("Failed to write summary: {}", e))?;
    writeln!(&mut script).map_err(|e| eyre::eyre!("Failed to write newline: {}", e))?;

    if diff.has_breaking_changes() {
        writeln!(&mut script, "-- WARNING: This upgrade contains breaking changes!")
            .map_err(|e| eyre::eyre!("Failed to write warning: {}", e))?;
        writeln!(&mut script, "-- Review carefully before applying to production.")
            .map_err(|e| eyre::eyre!("Failed to write warning: {}", e))?;
        writeln!(&mut script).map_err(|e| eyre::eyre!("Failed to write newline: {}", e))?;
    }

    // Process renames first
    if !diff.renamed.is_empty() {
        writeln!(&mut script, "-- Renamed entities")
            .map_err(|e| eyre::eyre!("Failed to write section header: {}", e))?;
        for rename in &diff.renamed {
            generate_rename_sql(&mut script, rename, pgrx_sql)?;
        }
        writeln!(&mut script).map_err(|e| eyre::eyre!("Failed to write newline: {}", e))?;
    }

    // Process removals (in reverse dependency order)
    if !diff.removed.is_empty() {
        writeln!(&mut script, "-- Removed entities")
            .map_err(|e| eyre::eyre!("Failed to write section header: {}", e))?;
        let removals = diff.removals_in_dependency_order();
        for removal in removals {
            generate_drop_sql(&mut script, removal, pgrx_sql)?;
        }
        writeln!(&mut script).map_err(|e| eyre::eyre!("Failed to write newline: {}", e))?;
    }

    // Process modifications
    if !diff.modified.is_empty() {
        writeln!(&mut script, "-- Modified entities")
            .map_err(|e| eyre::eyre!("Failed to write section header: {}", e))?;
        for modification in &diff.modified {
            generate_modify_sql(&mut script, modification, pgrx_sql)?;
        }
        writeln!(&mut script).map_err(|e| eyre::eyre!("Failed to write newline: {}", e))?;
    }

    // Process additions (in dependency order)
    if !diff.added.is_empty() {
        writeln!(&mut script, "-- Added entities")
            .map_err(|e| eyre::eyre!("Failed to write section header: {}", e))?;
        let additions = diff.additions_in_dependency_order();
        for addition in additions {
            generate_create_sql(&mut script, addition, pgrx_sql)?;
        }
        writeln!(&mut script).map_err(|e| eyre::eyre!("Failed to write newline: {}", e))?;
    }

    Ok(script)
}

/// Generate a DROP statement with SQL context.
fn generate_drop_sql(
    script: &mut String,
    change: &EntityChange,
    _pgrx_sql: &PgrxSql,
) -> eyre::Result<()> {
    writeln!(script, "-- Drop: {}", change.id.rust_identifier)
        .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
    if let (Some(file), Some(line)) = (change.entity.file(), change.entity.line()) {
        writeln!(script, "-- Source: {}:{}", file, line)
            .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
    }

    match &change.entity {
        SqlGraphEntitySnapshot::Function(func) => {
            // For removed functions, try to generate argument types from metadata
            // without requiring the current context (since the function was removed)
            let arg_types = generate_function_arg_types_from_metadata(func);

            writeln!(script, "DROP FUNCTION IF EXISTS {}({});", func.name, arg_types)
                .map_err(|e| eyre::eyre!("Failed to write DROP FUNCTION: {}", e))?;

            if !func.fn_args.is_empty() && arg_types.is_empty() {
                writeln!(
                    script,
                    "-- MANUAL REVIEW: Function had {} argument(s), but types couldn't be determined. Update signature.",
                    func.fn_args.len()
                )
                .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
            }
        }
        SqlGraphEntitySnapshot::Type(pg_type) => {
            writeln!(script, "DROP TYPE IF EXISTS {} CASCADE;", pg_type.name)
                .map_err(|e| eyre::eyre!("Failed to write DROP TYPE: {}", e))?;
            writeln!(script, "-- MANUAL REVIEW: CASCADE may drop dependent objects")
                .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
        }
        SqlGraphEntitySnapshot::Enum(enum_entity) => {
            writeln!(script, "DROP TYPE IF EXISTS {} CASCADE;", enum_entity.name)
                .map_err(|e| eyre::eyre!("Failed to write DROP TYPE: {}", e))?;
        }
        SqlGraphEntitySnapshot::Schema(schema) => {
            writeln!(script, "DROP SCHEMA IF EXISTS {} CASCADE;", schema.name)
                .map_err(|e| eyre::eyre!("Failed to write DROP SCHEMA: {}", e))?;
            writeln!(script, "-- MANUAL REVIEW: CASCADE will drop all objects in schema")
                .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
        }
        SqlGraphEntitySnapshot::Aggregate(agg) => {
            writeln!(script, "DROP AGGREGATE IF EXISTS {}(...);", agg.name)
                .map_err(|e| eyre::eyre!("Failed to write DROP AGGREGATE: {}", e))?;
            writeln!(script, "-- MANUAL REVIEW: Verify aggregate signature")
                .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
        }
        SqlGraphEntitySnapshot::Trigger(trigger) => {
            writeln!(
                script,
                "-- MANUAL REVIEW: Need table name to drop trigger: {}",
                trigger.function_name
            )
            .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
            writeln!(script, "-- DROP TRIGGER {} ON <table_name>;", trigger.function_name)
                .map_err(|e| eyre::eyre!("Failed to write DROP TRIGGER: {}", e))?;
        }
        _ => {
            writeln!(script, "-- Unable to generate DROP for: {}", change.id.rust_identifier)
                .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
        }
    }

    writeln!(script).map_err(|e| eyre::eyre!("Failed to write newline: {}", e))?;
    Ok(())
}

/// Generate a CREATE statement using the entity's ToSql implementation.
fn generate_create_sql(
    script: &mut String,
    change: &EntityChange,
    pgrx_sql: &PgrxSql,
) -> eyre::Result<()> {
    use crate::SqlGraphEntity;

    writeln!(script, "-- Create: {}", change.id.rust_identifier)
        .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
    if let (Some(file), Some(line)) = (change.entity.file(), change.entity.line()) {
        writeln!(script, "-- Source: {}:{}", file, line)
            .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
    }

    // Convert snapshot entity back to runtime entity for ToSql
    let runtime_entity = SqlGraphEntity::from(change.entity.clone());

    // Use the entity's ToSql implementation to generate the actual SQL
    let sql = runtime_entity.to_sql(pgrx_sql)?;
    writeln!(script, "{}", sql).map_err(|e| eyre::eyre!("Failed to write SQL: {}", e))?;

    writeln!(script).map_err(|e| eyre::eyre!("Failed to write newline: {}", e))?;
    Ok(())
}

/// Generate an ALTER or DROP/CREATE for a modified entity.
fn generate_modify_sql(
    script: &mut String,
    modification: &EntityModification,
    pgrx_sql: &PgrxSql,
) -> eyre::Result<()> {
    writeln!(script, "-- Modify: {}", modification.id.rust_identifier)
        .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
    if let (Some(file), Some(line)) =
        (modification.new_entity.file(), modification.new_entity.line())
    {
        writeln!(script, "-- Source: {}:{}", file, line)
            .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
    }
    writeln!(script, "-- Changes:").map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
    for change in &modification.changes {
        writeln!(script, "--   - {}", change)
            .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
    }

    match (&modification.old_entity, &modification.new_entity) {
        (SqlGraphEntitySnapshot::Function(_), SqlGraphEntitySnapshot::Function(new_func)) => {
            // Functions support CREATE OR REPLACE
            let sql = new_func.to_sql(pgrx_sql)?;
            writeln!(script, "{}", sql).map_err(|e| eyre::eyre!("Failed to write SQL: {}", e))?;
        }
        (SqlGraphEntitySnapshot::Enum(old_enum), SqlGraphEntitySnapshot::Enum(new_enum)) => {
            // Enums can only add values in PostgreSQL
            let old_variants: std::collections::HashSet<_> = old_enum.variants.iter().collect();
            let new_variants: std::collections::HashSet<_> = new_enum.variants.iter().collect();

            // Check for added variants
            for variant in &new_enum.variants {
                if !old_variants.contains(variant) {
                    writeln!(
                        script,
                        "ALTER TYPE {} ADD VALUE IF NOT EXISTS '{}';",
                        new_enum.name, variant
                    )
                    .map_err(|e| eyre::eyre!("Failed to write ALTER TYPE: {}", e))?;
                }
            }

            // Check for removed variants
            for variant in &old_enum.variants {
                if !new_variants.contains(variant) {
                    writeln!(
                        script,
                        "-- MANUAL REVIEW: Cannot remove enum value '{}' from {} - requires type recreation",
                        variant, old_enum.name
                    )
                    .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
                }
            }
        }
        (SqlGraphEntitySnapshot::Type(_old_type), SqlGraphEntitySnapshot::Type(new_type)) => {
            // Types usually need to be dropped and recreated
            writeln!(
                script,
                "-- Type {} was modified - may require DROP and recreate",
                new_type.name
            )
            .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
            writeln!(script, "-- MANUAL REVIEW: Type modifications often require data migration")
                .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
        }
        _ => {
            writeln!(
                script,
                "-- Unable to generate ALTER for: {}",
                modification.id.rust_identifier
            )
            .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
        }
    }

    writeln!(script).map_err(|e| eyre::eyre!("Failed to write newline: {}", e))?;
    Ok(())
}

/// Generate RENAME or DROP/CREATE for a renamed entity.
fn generate_rename_sql(
    script: &mut String,
    rename: &EntityRename,
    _pgrx_sql: &PgrxSql,
) -> eyre::Result<()> {
    writeln!(
        script,
        "-- Rename: {} -> {} (confidence: {:.0}%)",
        rename.old_id.rust_identifier,
        rename.new_id.rust_identifier,
        rename.confidence * 100.0
    )
    .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
    writeln!(script, "-- MANUAL REVIEW: Verify this rename is correct")
        .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;

    match (&rename.old_entity, &rename.new_entity) {
        (SqlGraphEntitySnapshot::Function(old_fn), SqlGraphEntitySnapshot::Function(new_fn)) => {
            writeln!(script, "-- ALTER FUNCTION {}(...) RENAME TO {};", old_fn.name, new_fn.name)
                .map_err(|e| eyre::eyre!("Failed to write ALTER FUNCTION: {}", e))?;
            writeln!(script, "-- Note: Function signature must match exactly")
                .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
        }
        (SqlGraphEntitySnapshot::Type(old_type), SqlGraphEntitySnapshot::Type(new_type)) => {
            writeln!(script, "ALTER TYPE {} RENAME TO {};", old_type.name, new_type.name)
                .map_err(|e| eyre::eyre!("Failed to write ALTER TYPE: {}", e))?;
        }
        (SqlGraphEntitySnapshot::Enum(old_enum), SqlGraphEntitySnapshot::Enum(new_enum)) => {
            writeln!(script, "ALTER TYPE {} RENAME TO {};", old_enum.name, new_enum.name)
                .map_err(|e| eyre::eyre!("Failed to write ALTER TYPE: {}", e))?;
        }
        (
            SqlGraphEntitySnapshot::Schema(old_schema),
            SqlGraphEntitySnapshot::Schema(new_schema),
        ) => {
            writeln!(script, "ALTER SCHEMA {} RENAME TO {};", old_schema.name, new_schema.name)
                .map_err(|e| eyre::eyre!("Failed to write ALTER SCHEMA: {}", e))?;
        }
        _ => {
            writeln!(
                script,
                "-- Unable to generate RENAME for: {} -> {}",
                rename.old_id.rust_identifier, rename.new_id.rust_identifier
            )
            .map_err(|e| eyre::eyre!("Failed to write comment: {}", e))?;
        }
    }

    writeln!(script).map_err(|e| eyre::eyre!("Failed to write newline: {}", e))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::diff::SchemaDiff;
    use crate::schema::entity::SchemaEntity;
    use crate::snapshot::{EntityId, SchemaSnapshot, SerializableEntity};
    use std::time::SystemTime;

    #[test]
    fn test_empty_upgrade_script() {
        let snapshot1 = SchemaSnapshot {
            version: "1.0.0".to_string(),
            timestamp: SystemTime::now(),
            extension_name: "test".to_string(),
            entities: vec![],
            dependency_edges: vec![],
            versioned_so: false,
        };

        let snapshot2 = snapshot1.clone();

        let diff = SchemaDiff::compare(&snapshot1, &snapshot2);
        let config = UpgradeConfig::default();

        let script = generate_upgrade_script(&diff, &config).unwrap();

        assert!(script.contains("from version 1.0.0 to 1.0.0"));
        assert!(!script.contains("DROP"));
        assert!(!script.contains("CREATE"));
    }

    #[test]
    fn test_schema_addition() {
        let snapshot1 = SchemaSnapshot {
            version: "1.0.0".to_string(),
            timestamp: SystemTime::now(),
            extension_name: "test".to_string(),
            entities: vec![],
            dependency_edges: vec![],
            versioned_so: false,
        };

        let schema_entity = SchemaEntity {
            module_path: "test::schema",
            name: "test_schema",
            file: "src/lib.rs",
            line: 10,
        };

        let mut snapshot2 = snapshot1.clone();
        snapshot2.version = "1.1.0".to_string();
        snapshot2.entities.push(SerializableEntity {
            id: EntityId::from_entity(&crate::SqlGraphEntity::Schema(schema_entity.clone())),
            entity: SqlGraphEntitySnapshot::Schema(schema_entity),
            node_index: Some(0),
        });

        let diff = SchemaDiff::compare(&snapshot1, &snapshot2);
        let config = UpgradeConfig::default();

        let script = generate_upgrade_script(&diff, &config).unwrap();

        assert!(script.contains("CREATE SCHEMA"));
        assert!(script.contains("test_schema"));
    }
}
